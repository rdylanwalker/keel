//! Embeds every built-in catalog entry (`deploy/catalog/{apps,infra,bundles}/**`) into the `keel`
//! binary so `keel bootstrap init` seeds the whole self-service catalog into the GitOps repository.
//!
//! Generates `$OUT_DIR/built_in_catalog.rs` with `BUILT_IN_CATALOG_FILES`, a sorted list of
//! `(repository path, contents)` pairs (`catalog/apps/<id>/catalog.yaml`, ...). `catalog/core` is
//! not included: those management-plane entries are seeded conditionally by bootstrap itself.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::{env, fs};

/// Seeded catalog kinds (`deploy/catalog/<kind>/<id>/...`).
const SEEDED_KINDS: &[&str] = &["apps", "infra", "bundles"];

/// File names the catalog loaders read. Any other (non-hidden) file under a seeded kind fails the
/// build, so stray local files (e.g. `Pulumi.<stack>.yaml`) never end up in an operator's GitOps
/// repository and new file kinds have to be allowed here on purpose.
const ALLOWED_FILE_NAMES: &[&str] = &["catalog.yaml", "Pulumi.yaml", "manifests.yaml"];

fn collect_files(dir: &Path, out: &mut Vec<PathBuf>) {
    let mut entries: Vec<PathBuf> = fs::read_dir(dir)
        .unwrap_or_else(|e| panic!("read {}: {e}", dir.display()))
        .map(|entry| entry.expect("directory entry").path())
        .collect();
    entries.sort();
    for path in entries {
        let name = path
            .file_name()
            .and_then(|n| n.to_str())
            .unwrap_or_else(|| panic!("non UTF-8 catalog path {}", path.display()));
        // Hidden entries (editor swap files, `.DS_Store`, ...) are never part of the catalog.
        if name.starts_with('.') {
            continue;
        }
        if path.is_dir() {
            collect_files(&path, out);
        } else if path.is_file() {
            assert!(
                ALLOWED_FILE_NAMES.contains(&name),
                "unexpected built-in catalog file {} (allowed: {ALLOWED_FILE_NAMES:?}); \
                 remove it or add its name to ALLOWED_FILE_NAMES in crates/keel-cli/build.rs",
                path.display()
            );
            out.push(path);
        }
    }
}

fn main() {
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let catalog_root = manifest_dir.join("../../deploy/catalog");
    let catalog_root = catalog_root
        .canonicalize()
        .unwrap_or_else(|e| panic!("resolve {}: {e}", catalog_root.display()));

    let mut files = Vec::new();
    for kind in SEEDED_KINDS {
        let dir = catalog_root.join(kind);
        println!("cargo:rerun-if-changed={}", dir.display());
        collect_files(&dir, &mut files);
    }

    let mut out = String::from(
        "/// Every built-in `deploy/catalog/{apps,infra,bundles}` file as `(repository path, contents)`,\n\
         /// sorted by path (generated by `build.rs`).\n\
         pub(crate) const BUILT_IN_CATALOG_FILES: &[(&str, &str)] = &[\n",
    );
    for file in &files {
        let rel = file
            .strip_prefix(&catalog_root)
            .expect("catalog file under deploy/catalog");
        let rel = rel
            .to_str()
            .unwrap_or_else(|| panic!("non UTF-8 catalog path {}", rel.display()))
            .replace(std::path::MAIN_SEPARATOR, "/");
        let abs = file
            .to_str()
            .unwrap_or_else(|| panic!("non UTF-8 catalog path {}", file.display()));
        writeln!(
            out,
            "    ({:?}, include_str!({abs:?})),",
            format!("catalog/{rel}")
        )
        .expect("write to String");
    }
    out.push_str("];\n");

    let dest = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR")).join("built_in_catalog.rs");
    fs::write(&dest, out).unwrap_or_else(|e| panic!("write {}: {e}", dest.display()));
}
